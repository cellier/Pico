import AppKit

@main struct KeyDisplayTests {
    @MainActor static func main() {
        let name = "TelosKeyDisplayTests.\(UUID().uuidString)"
        let defaults = UserDefaults(suiteName: name)!
        defer { defaults.removePersistentDomain(forName: name) }
        precondition(KeyDisplayLabel.enabled(in: defaults))
        let controller = KeyDisplayController(defaults: defaults)
        precondition(controller.enabled)
        controller.setEnabled(false)
        precondition(!KeyDisplayLabel.enabled(in: defaults))
        precondition(!controller.monitoring)
        precondition(!KeyDisplayController(defaults: defaults).enabled)
        precondition(KeyDisplayLabel.text(code: 0, characters: "a", flags: [.command], secure: false) == "⌘A")
        precondition(KeyDisplayLabel.text(code: 8, characters: "c", flags: [.control, .option, .shift, .command], secure: false) == "⌃⌥⇧⌘C")
        precondition(KeyDisplayLabel.text(code: 48, characters: "\t", flags: [.shift], secure: false) == "⇧Tab")
        precondition(KeyDisplayLabel.text(code: 123, characters: nil, flags: [.command], secure: false) == "⌘←")
        precondition(KeyDisplayLabel.text(code: 122, characters: nil, flags: [], secure: false) == "F1")
        precondition(KeyDisplayLabel.text(code: 49, characters: " ", flags: [], secure: false) == "Space")
        precondition(KeyDisplayLabel.text(code: 51, characters: "\u{7f}", flags: [], secure: false) == "⌫")
        precondition(KeyDisplayLabel.text(code: 0, characters: "密", flags: [], secure: true) == nil)
        precondition(KeyDisplayLabel.text(code: 0, characters: "secret", flags: [], secure: false) == nil)
        precondition(KeyDisplayLabel.text(code: 0, characters: "\u{1}", flags: [], secure: false) == nil)
        var hold = KeyDisplayHold()
        precondition(!hold.isHeld)
        precondition(hold.modifiersChanged([.command, .shift]) == "⇧⌘")
        precondition(hold.isHeld)
        hold.keyPressed(0, flags: [.command, .shift])
        precondition(hold.modifiersChanged([.command]) == nil)
        hold.keyReleased(0)
        precondition(hold.isHeld, "Command still holds the shortcut on screen")
        precondition(hold.modifiersChanged([]) == nil)
        precondition(!hold.isHeld, "Countdown can begin only after every key is released")
        precondition(hold.modifiersChanged([.option]) == "⌥")
        precondition(hold.isHeld)
        precondition(hold.modifiersChanged([]) == "")
        precondition(!hold.isHeld)
        hold.keyPressed(0, flags: [])
        hold.keyPressed(0, flags: []) // Auto-repeat is one physical key.
        hold.keyPressed(8, flags: [])
        hold.keyReleased(0)
        precondition(hold.isHeld, "Another held key must keep the overlay visible")
        hold.keyReleased(8)
        precondition(!hold.isHeld)
        hold.functionChanged(true)
        precondition(hold.isHeld)
        hold.keyPressed(123, flags: [.function])
        hold.keyReleased(123)
        precondition(hold.isHeld, "Fn remains held after the arrow is released")
        hold.functionChanged(false)
        precondition(!hold.isHeld)
        hold.keyPressed(123, flags: [.function])
        hold.keyReleased(123)
        precondition(!hold.isHeld, "Arrow event flags must not imply a physically held Fn key")
        _ = hold.modifiersChanged([.capsLock])
        precondition(!hold.isHeld, "Caps Lock's toggled state must not hold the overlay forever")
        hold.keyPressed(0, flags: [])
        precondition(hold.isHeld)
        hold = KeyDisplayHold()
        precondition(!hold.isHeld, "Secure input and monitoring interruption reset held state")
        print("PASS: preferences, labels, secure input suppression, held keys, modifiers, Fn, auto-repeat, and release ordering")
    }
}
