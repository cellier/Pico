#!/usr/bin/env python3
"""Bundle the existing Pico mesh renderer as a self-contained app resource."""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[1]
pico = root / 'Pico'
three = (pico / 'vendor/three.module.js').read_text()
three = re.sub(r'export \{[^}]+\};\s*$', '', three)
sources = [three]
sources.extend((pico / name).read_text() for name in ('eyes.js', 'flower.js', 'orb.js', 'pet.js'))
sources.append((root / 'Resources/PicoAvatarBridge.js').read_text())
javascript = '\n'.join(sources).replace('messageHandlers.native.postMessage', 'messageHandlers.native?.postMessage')
# The header's native web surface may be paused or redrawn by AppKit between
# animation frames. Retain its tiny canvas instead of presenting a cleared frame.
javascript = javascript.replace("powerPreference:'low-power'", "powerPreference:'low-power',preserveDrawingBuffer:true")
html = '''<!doctype html>
<!-- Generated by scripts/build-pico-avatar.py from the existing Pico3D companion.
Three.js r160; MIT license retained in Resources/PicoAvatar-LICENSE.txt. -->
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; img-src data:; connect-src 'none'">
<style>html,body{margin:0;width:100%;height:100%;background:transparent;overflow:hidden;pointer-events:none}canvas{display:block;width:100%;height:100%}</style>
<script type="module">''' + javascript + '</script>\n'
(root / 'Resources/PicoAvatar.html').write_text(html)
(root / 'Resources/PicoAvatar-LICENSE.txt').write_text((pico / 'vendor/LICENSE').read_text())
print('Generated Resources/PicoAvatar.html from the shared Pico renderer.')
